// LookupVendor 返回 MAC 地址 OUI 前缀对应的厂商名。
// 全零/非 6 字节 MAC 一律返回 "Unknown"；首字节 bit1（本地管理位）置位表示
// MAC 是随机化的（iOS/Android Wi-Fi 隐私、Windows 随机硬件地址），返回 "随机化"
// 而非 "Unknown"，让用户一眼区分"查不到 OUI"和"系统故意隐藏了真实 OUI"。
func LookupVendor(mac net.HardwareAddr) string {
	if len(mac) != 6 || bytes.Equal(mac, zeroMAC) {
		return "Unknown"
	}

	// IEEE 802 规范：首字节 bit0 是 I/G（个体/组），bit1 是 U/L（全局/本地）。
	// U/L=1 表示地址由系统本地分配而非 IEEE 分配，即随机化 MAC。
	if mac[0]&0x02 != 0 {
		return "随机化"
	}

	if vendor, ok := ouiTable[[3]byte{mac[0], mac[1], mac[2]}]; ok {
		return vendor
	}

	return "Unknown"
}
